#!/usr/bin/env python3
"""Generate Ren'Py image declarations and layeredimage blocks from PNG frames."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

DEFAULT_ROOT = Path(__file__).resolve().parent.parent
IDENTIFIER = re.compile(r"^[a-z][a-z0-9_]*$")
GROUPS = {
    "base": ("idle", "walk", "work", "hurt"),
    "face": ("neutral", "smile", "soft", "surprise", "angry", "pain"),
    "blush": ("off", "on"),
}


def resolve_frame(images: Path, character: str, prefix: str, attribute: str) -> str:
    """Accept explicit prefixed frame names, with short base names as aliases."""
    candidates = [f"{prefix}_{attribute}", attribute]
    found = [name for name in candidates if (images / character / f"{name}.png").is_file()]
    if not found:
        raise ValueError(f"{character}: missing {prefix} group member {attribute!r} (expected one of {candidates})")
    if len(found) > 1:
        raise ValueError(f"{character}: ambiguous {prefix} member {attribute!r}; found {', '.join(found)}")
    return found[0]


def generate(images: Path, output: Path) -> None:
    if not images.is_dir():
        raise ValueError(f"Image directory does not exist: {images}")
    characters = sorted(p.name for p in images.iterdir() if p.is_dir())
    if not characters:
        raise ValueError(f"No character directories found under {images}")

    frames_by_character: dict[str, list[str]] = {}
    groups_by_character: dict[str, dict[str, dict[str, str]]] = {}
    for character in characters:
        if not IDENTIFIER.fullmatch(character):
            raise ValueError(f"Invalid Ren'Py character identifier: {character!r}")
        files = sorted(p for p in (images / character).glob("*.png") if p.is_file())
        if not files:
            raise ValueError(f"No PNG frames found for {character}")
        frames = [p.stem for p in files]
        for frame in frames:
            if not IDENTIFIER.fullmatch(frame):
                raise ValueError(f"Invalid Ren'Py frame identifier: {frame!r}")
        frames_by_character[character] = frames
        groups_by_character[character] = {
            group: {
                attribute: resolve_frame(images, character, group, attribute)
                for attribute in attributes
            }
            for group, attributes in GROUPS.items()
        }

    lines = [
        "# Generated by tools/imagesrpy.py. Edit the source PNG set, not this file.",
        "init python:",
        "    config.say_attribute_transition = Dissolve(0.15)",
        "",
    ]
    for character in characters:
        for frame in frames_by_character[character]:
            lines.append(f'image {character} {frame} = "images/{character}/{frame}.png"')
        lines.append("")

    for character in characters:
        group_frames = groups_by_character[character]
        idle_frame = group_frames["base"]["idle"]
        lines.extend(
            [
                f"layeredimage {character}:",
                "    # Idle is the default base layer and is explicitly always displayed.",
                "    always:",
                f'        "{character} {idle_frame}"',
                "        when idle",
                "",
                "    group base:",
                "        attribute idle default",
            ]
        )
        for attribute in GROUPS["base"][1:]:
            frame = group_frames["base"][attribute]
            lines.extend([f"        attribute {attribute}:", f'            "{character} {frame}"'])
        for group in ("face", "blush"):
            lines.extend(["", f"    group {group}:"])
            for index, attribute in enumerate(GROUPS[group]):
                frame = group_frames[group][attribute]
                default = " default" if index == 0 else ""
                lines.extend(
                    [
                        f"        attribute {attribute}{default}:",
                        f'            "{character} {frame}"',
                    ]
                )
        lines.append("")

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"generated {output} for {len(characters)} character(s)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--images", type=Path, default=DEFAULT_ROOT / "game/images")
    parser.add_argument("--output", type=Path, default=DEFAULT_ROOT / "game/definitions.rpy")
    args = parser.parse_args()
    try:
        generate(args.images, args.output)
    except (OSError, ValueError) as exc:
        print(f"imagesrpy: ERROR: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
